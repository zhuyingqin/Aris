// Generate the shell DTOs from their Rust source without adding a build dependency.
// Unsupported shapes fail explicitly so protocol edits cannot silently drift.
const fs = require("node:fs");
const path = require("node:path");
const source = path.resolve(__dirname, "../../crates/remote-protocol/src/code_bridge.rs");
const output = path.resolve(__dirname, "../src/code/codeShell.ts");
const rust = fs.readFileSync(source, "utf8");
const camel = (name) => name.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
const kebab = (name) => name.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
function type(value) {
  value = value.trim();
  if (value === "String") return "string";
  if (value === "bool") return "boolean";
  if (value === "u8") return "number";
  if (/^CodeShell\w+$/.test(value)) return value;
  const option = value.match(/^Option<(.+)>$/);
  if (option) return `${type(option[1])} | null`;
  const vector = value.match(/^Vec<(.+)>$/);
  if (vector) return `${type(vector[1])}[]`;
  throw new Error(`Unsupported Rust shell type: ${value}`);
}
let generated = "// Generated by scripts/generate-code-shell-types.cjs from remote-protocol.\n// Do not edit directly.\n";
for (const name of ["CodeShellState", "CodeShellModule", "CodeShellProject", "CodeShellAccount"]) {
  const body = rust.match(new RegExp(`#\\[serde\\(rename_all = "camelCase"\\)\\]\\s*pub struct ${name} \\{([^}]+)\\}`))?.[1];
  if (!body) throw new Error(`Missing camelCase Rust struct: ${name}`);
  const fields = [...body.matchAll(/pub (\w+): ([^,]+),/g)];
  if (!fields.length || body.replace(/pub \w+: [^,]+,/g, "").trim()) throw new Error(`Unsupported fields: ${name}`);
  generated += `\nexport interface ${name} {\n${fields.map(([, field, value]) => `  ${camel(field)}: ${type(value)};`).join("\n")}\n}\n`;
}
const action = rust.match(/#\[serde\(tag = "kind", rename_all = "kebab-case"\)\]\s*pub enum CodeShellAction \{([\s\S]*?)\n\}/)?.[1];
if (!action) throw new Error("Missing tagged CodeShellAction enum");
const variantPattern = /(\w+)(?:\s*\{\s*(\w+):\s*(\w+),?\s*\})?,/g;
if (action.replace(variantPattern, "").trim()) throw new Error("Unsupported CodeShellAction shape");
const variants = [...action.matchAll(variantPattern)].map((match) => {
  return `  | { kind: "${kebab(match[1])}"${match[2] ? `; ${camel(match[2])}: ${type(match[3])}` : ""} }`;
});
generated += `\nexport type CodeShellAction =\n${variants.join("\n")};\n`;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== generated) {
    throw new Error("Shell types are stale. Run node scripts/generate-code-shell-types.cjs");
  }
} else {
  fs.writeFileSync(output, generated);
}
