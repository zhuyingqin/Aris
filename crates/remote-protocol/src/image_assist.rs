    #[test]
    fn a_transcript_frame_is_validated_by_the_decoder_itself() {
        // The transcript is the first frame on the channel, so it is decoded
        // before any Image Assist state exists to check it. Frame validation is
        // therefore the only thing standing between a malformed transcript and
        // the verification path.
        let requester = device("requester laptop");
        let helper = device("helper workstation");
        let mut transcript = transcript(&requester, &helper);
        let proof = transcript.sign(&helper.signing).expect("helper signs");

        let frame = ImageAssistWireMessage::Transcript {
            transcript: Box::new(transcript.clone()),
            proof: proof.clone(),
        };
        assert_eq!(frame.validate(), Ok(()));
        let encoded = serde_json::to_value(&frame).expect("transcript frame encodes");
        assert_eq!(encoded["type"], "image_transcript");
        assert!(serde_json::from_value::<ComputeWireMessage>(encoded).is_err());

        transcript.ice_servers = vec![
            "stun:b.example.test:3478".to_string(),
            "stun:a.example.test:3478".to_string(),
        ];
        assert_eq!(
            ImageAssistWireMessage::Transcript {
                transcript: Box::new(transcript),
                proof,
            }
            .validate(),
            Err(ImageAssistError::UnsortedIceServers)
        );
    }

