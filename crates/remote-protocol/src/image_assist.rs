    #[test]
    fn the_preview_key_is_domain_separated_from_the_transport_key() {
        // Even when a match id and a transport session id carry the same UUID,
        // the two derivations must not collide: a shared key would let a
        // preview envelope consume the transport replay window.
        let requester = device("requester laptop");
        let helper = device("helper workstation");
        let shared = uuid::Uuid::new_v4();

        let preview = requester
            .agreement
            .derive_preview_key(
                &helper.descriptor.key_agreement_public_key,
                &PreviewKeyContext::new(
                    MatchId::from_uuid(shared),
                    requester.descriptor.device_id,
                    helper.descriptor.device_id,
                )
                .expect("preview context"),
            )
            .expect("preview key");
        let transport = requester
            .agreement
            .derive_session_key(
                &helper.descriptor.key_agreement_public_key,
                &SessionKeyContext::new(
                    SessionId::from_uuid(shared),
                    requester.descriptor.device_id,
                    helper.descriptor.device_id,
                )
                .expect("session context"),
            )
            .expect("transport key");

        assert_ne!(preview.as_bytes(), transport.as_bytes());
    }

