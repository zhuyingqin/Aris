        // name would let a malicious introducer relabel who is asking.
        let requester = device("requester laptop");
        let helper = device("helper workstation");
        let transcript = transcript(&requester, &helper);
        let proof = transcript
            .sign(&requester.signing)
            .expect("requester signs");

